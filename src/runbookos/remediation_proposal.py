def proposal_prompt(
    *,
    incident_id: str,
    investigation_id: str,
    evidence: list[dict[str, Any]],
    candidates: list[RegisteredActionCandidate],
) -> str:
    """Create a bounded prompt from observed evidence and trusted action candidates."""
    _reject_gold_leakage(evidence)
    payload = {
        "incident_id": incident_id,
        "investigation_id": investigation_id,
        "evidence": evidence,
        "registered_action_candidates": [
            {
                **item.model_dump(mode="json"),
                "observed_unit_prerequisite": unit_state_prerequisite(item, evidence),
                "observed_repair_prerequisite": candidate_observation_prerequisite(item, evidence),
            }
            for item in candidates
        ],
    }
    encoded = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    if len(encoded.encode("utf-8")) > 64 * 1024:
        raise RunbookOSError("AI remediation context exceeds the configured size limit")
    return encoded


_GOLD_KEYS = {
    "gold",
    "goldlabel",
    "goldclassification",
    "groundtruth",
    "groundtruthcategory",
    "expected",
    "expectedlabel",
    "expectedabstention",
    "annotationrationale",
    "caserationale",
    "oracle",
}


def _reject_gold_leakage(value: Any) -> None:
    if isinstance(value, dict):
        if any(re.sub(r"[^a-z0-9]", "", str(key).casefold()) in _GOLD_KEYS for key in value):
            raise RunbookOSError(
                "model-facing remediation context contains reserved label metadata"
            )
        for child in value.values():
            _reject_gold_leakage(child)
    elif isinstance(value, list):
        for child in value:
            _reject_gold_leakage(child)


